export type NameStyle = keyof typeof STYLES;

/** The naming style of a species, by its name (any species of the character builder). */
export function styleFor(species: string): NameStyle {
  const s = species.toLowerCase();
  const has = (...words: string[]) => words.some((w) => s.includes(w));
  if (has('elf', 'drow', 'eladrin', 'shadar')) return 'elf';
  if (has('dwarf', 'duergar')) return 'dwarf';
  if (has('halfling')) return 'halfling';
  if (has('gnome', 'svirfneblin', 'autognome')) return has('autognome') ? 'construct' : 'gnome';
  if (has('orc')) return 'orc';
  if (has('tiefling')) return 'tiefling';
  if (has('dragonborn', 'dragon')) return 'dragonborn';
  if (has('goliath', 'firbolg', 'giant')) return 'giant';
  if (has('goblin', 'kobold', 'bugbear')) return 'goblin';
  if (has('aasimar')) return 'celestial';
  if (has('genasi', 'elemental')) return 'elemental';
  if (has('tabaxi', 'leonin', 'cat')) return 'feline';
  if (has('aven', 'aarakocra', 'kenku', 'owlin', 'bird')) return 'avian';
  if (has('tortle', 'lizard', 'yuan', 'triton', 'grung')) return 'reptile';
  if (has('warforged', 'construct', 'automaton')) return 'construct';
  return 'human';
}

/** A name in the style of a species; `gender` is woman, man or anything else. */
export function makeName(species: string, gender: string, rng: Rng = Math.random): string {
  const style: Style = STYLES[styleFor(species)];
  const ending =
    gender === 'woman' ? style.end[1] : gender === 'man' ? style.end[0] : pick(style.end, rng);
  const given = `${pick(style.start, rng)}${pick(style.middle, rng)}${pick(ending, rng)}`;
  if (!style.family || rng() > (style.familyChance ?? 1)) return given;
  const family = pick(style.family, rng);
  return style.join === ' "' ? `${given} "${family}"` : `${given}${style.join ?? ' '}${family}`;
}

/** Built-in species for when the builder's list is not loaded (no 5etools data yet). */
export const BASIC_SPECIES = [
  'Human',
  'Elf',
  'Dwarf',
  'Halfling',
  'Gnome',
  'Orc',
  'Tiefling',
  'Dragonborn',
  'Goliath',
  'Aasimar',
] as const;

/** `count` names, of one species or of any in `species` (each name says whose it is). */
export function generateNames(
  count: number,
  species: readonly string[],
  only?: string,
  rng: Rng = Math.random,
): { name: string; species: string }[] {
  const pool = species.length ? species : BASIC_SPECIES;
  return Array.from({ length: Math.max(1, Math.min(100, Math.round(count))) }, () => {
    const sp = only ?? pick(pool, rng);
    const gender = rng() < 0.5 ? 'woman' : 'man';
    return { name: makeName(sp, gender, rng), species: sp };
  });
}
