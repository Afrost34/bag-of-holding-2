/**
 * Names for NPCs and the name generator: a naming style per kind of species (syllables to start,
 * maybe a middle, an ending by gender, sometimes a family name or a clan/epithet). Any species
 * of the character builder maps to a style by its name (High Elf → elvish, Aven → avian…). The
 * syllables are the app's own, so generated names are the DM's to keep.
 */

export type Rng = () => number;

export const pick = <T>(list: readonly T[], rng: Rng): T =>
  list[Math.floor(rng() * list.length)] as T;

interface Style {
  start: readonly string[];
  middle: readonly string[];
  /** Endings for men, for women; people of other genders take either. */
  end: readonly [readonly string[], readonly string[]];
  /** Family names, clans or epithets, after the given name. */
  family?: readonly string[];
  /** How often a family name is added (0–1); always when absent. */
  familyChance?: number;
  /** Joins given and family name (" " by default; " of the " for clans…). */
  join?: string;
}

